import { parseArgs } from 'node:util';
import { readFileSync,writeFileSync } from 'node:fs';
const {values}=parseArgs({options:{name:{type:'string'},description:{type:'string'},currency:{type:'string'},locale:{type:'string'}}});
const old=readFileSync('src/template.config.ts','utf8');
const match=old.match(/= (\{[\s\S]*\})\s*(?:as const)?;/);
if(!match)throw new Error('Configuration format changed. Edit src/template.config.ts directly.');
const config=JSON.parse(match[1]);
for(const key of ['name','description','currency','locale'])if(values[key])config[key]=values[key];
if(!/^[A-Z]{3}$/.test(config.currency))throw new Error('Currency must be a 3-letter uppercase ISO code.');
new Intl.NumberFormat(config.locale,{style:'currency',currency:config.currency});
writeFileSync('src/template.config.ts',old.slice(0,match.index)+'= '+JSON.stringify(config,null,2)+';\n');
console.info('Brand configuration updated. Existing product prices and currencies were NOT converted.');
